-- Private, member-attributed beta feedback inbox.
-- Members submit through a JWT-authenticated Neon Function; only the database
-- owner can review rows. No member API role may SELECT, UPDATE or DELETE.
CREATE TABLE app_private.site_feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES neon_auth."user"(id) ON DELETE SET NULL,
  page_path text NOT NULL CHECK (char_length(page_path) BETWEEN 1 AND 240),
  message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 1200),
  submitted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX site_feedback_recent_idx ON app_private.site_feedback (submitted_at DESC);
CREATE INDEX site_feedback_member_recent_idx ON app_private.site_feedback (user_id, submitted_at DESC);
REVOKE ALL ON app_private.site_feedback FROM PUBLIC, ogcupid_member_api, ogcupid_delete_api;
REVOKE ALL ON SEQUENCE app_private.site_feedback_id_seq FROM PUBLIC, ogcupid_member_api, ogcupid_delete_api;
ALTER TABLE app_private.site_feedback ENABLE ROW LEVEL SECURITY;
-- No member policies: even accidental direct grants are not enough to read it.

CREATE FUNCTION app_private.submit_site_feedback(p_message text, p_page_path text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app_private
AS $fn$
DECLARE
  member_id uuid;
  feedback_id bigint;
BEGIN
  member_id := nullif(current_setting('app.current_user_id', true), '')::uuid;
  IF member_id IS NULL OR
     NOT EXISTS (SELECT 1 FROM neon_auth."user" u WHERE u.id = member_id) THEN
    RAISE EXCEPTION 'Member session required' USING ERRCODE = '42501';
  END IF;
  IF p_message IS NULL OR char_length(trim(p_message)) < 1 OR
     char_length(p_message) > 1200 OR
     p_page_path IS NULL OR (p_page_path !~ '^/[A-Za-z0-9_./~-]*$' OR p_page_path LIKE '//%') OR
     char_length(p_page_path) > 240 THEN
    RAISE EXCEPTION 'Invalid feedback' USING ERRCODE = '22023';
  END IF;

  -- Serialize each member's submissions so parallel tabs can't beat limits.
  PERFORM pg_advisory_xact_lock(60612, hashtext(member_id::text));
  IF (SELECT count(*) FROM app_private.site_feedback
      WHERE user_id = member_id AND submitted_at > now() - interval '1 minute') >= 2 OR
     (SELECT count(*) FROM app_private.site_feedback
      WHERE user_id = member_id AND submitted_at > now() - interval '1 day') >= 30 THEN
    RAISE EXCEPTION 'Too many feedback submissions' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO app_private.site_feedback(user_id, page_path, message)
    VALUES (member_id, p_page_path, trim(p_message))
    RETURNING id INTO feedback_id;
  RETURN feedback_id;
END;
$fn$;
REVOKE ALL ON FUNCTION app_private.submit_site_feedback(text, text) FROM PUBLIC, ogcupid_delete_api;
GRANT EXECUTE ON FUNCTION app_private.submit_site_feedback(text, text) TO ogcupid_member_api;

