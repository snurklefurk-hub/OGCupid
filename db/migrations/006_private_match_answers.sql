-- Apply only to the isolated development branch before deploying the answer API.
CREATE TABLE IF NOT EXISTS app_private.published_match_questions (
  question_id text PRIMARY KEY,
  option_ids text[] NOT NULL
);
REVOKE ALL ON app_private.published_match_questions FROM PUBLIC;
GRANT SELECT ON app_private.published_match_questions TO ogcupid_member_api;

CREATE TABLE IF NOT EXISTS app_private.member_match_answers (
  user_id uuid NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  question_id text NOT NULL CHECK (question_id ~ '^vault-[0-9]+$' AND length(question_id) <= 32),
  option_id text NOT NULL CHECK (option_id ~ '^option-[0-9]+$' AND length(option_id) <= 32),
  acceptable_options text[] NOT NULL DEFAULT '{}',
  importance integer NOT NULL DEFAULT 1 CHECK (importance IN (0, 1, 10, 50, 250)),
  is_private boolean NOT NULL DEFAULT false,
  note text NOT NULL DEFAULT '' CHECK (char_length(note) <= 400),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, question_id),
  CONSTRAINT acceptable_options_valid CHECK (
    array_position(acceptable_options, NULL) IS NULL AND
    (cardinality(acceptable_options) = 0 OR
     array_to_string(acceptable_options, ',') ~ '^(option-[0-9]+)(,option-[0-9]+)*$')
  )
);
REVOKE ALL ON app_private.member_match_answers FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE ON app_private.member_match_answers TO ogcupid_member_api;
ALTER TABLE app_private.member_match_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.member_match_answers FORCE ROW LEVEL SECURITY;
CREATE POLICY member_match_answers_owner_only ON app_private.member_match_answers
  FOR ALL USING (user_id::text = NULLIF(current_setting('app.current_user_id', true), ''))
  WITH CHECK (user_id::text = NULLIF(current_setting('app.current_user_id', true), ''));

